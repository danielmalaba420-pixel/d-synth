# Renders the approved D-SYNTH 2.0 mockup (artifact "D-SYNTH 2.0 — nouvelle interface") into the plugin skin:
#   skin_bg.png    everything that never moves (2x)
#   skin_on.png    same, with every category button pressed and its LED lit (the plugin copies the selected one)
#   SkinRects.h    positions of every moving part, measured in the page
import json, os, sys
from playwright.sync_api import sync_playwright
here=os.path.dirname(os.path.abspath(__file__)); root=os.path.abspath(os.path.join(here,'..','..'))
S=[["Rising Run","LEAD"],["The Run","LEAD"],["Flute Synth","LEAD"],["Supersaw","LEAD"],["Afro Pluck","LEAD"],["Signly","LEAD"],["Arp Pulse","ARP"],["Arp Crystal","ARP"],["Arp Drive","ARP"],["String Glide","NAPPE"],["String Dinsei","NAPPE"],["The Prayer","NAPPE"],["Holy G","CLAVIER"],["Fire Keys","CLAVIER"],["Glory Brass","CUIVRE"],["Finger Bass","BASSE"],["Synth Bass","BASSE"],["Sub Bass","BASSE"],["Riser","FX"],["FX Kit","FX"]]
C=["TOUS","FAVORIS","LEAD","ARP","NAPPE","CLAVIER","CUIVRE","BASSE","FX"]
def page(mode):
    on = mode=='on'
    pad=lambda n:("0" if n<10 else "")+str(n)
    rows="".join(f'<div data-id="row" class="row{" sel" if i==9 else ""}"><span>{pad(i+1)}  {S[i][0].upper()}</span><span></span></div>' for i in range(6,14))
    cats="".join(f'<div data-id="cat" style="flex:1;"><div class="led{" on" if on else ""}"></div><button class="cb{" on" if on else ""}">{"★ FAVORIS" if c=="FAVORIS" else c}</button></div>' for c in C)
    W=1010/21
    wn=[0,2,4,5,7,9,11]; bn=[1,3,6,8,10]
    blacks="".join(f'<div class="bk" data-id="key" data-note="{36+o*12+bn[j]}" style="left:{round((o*7+k+1)*W-15)}px;"></div>' for o in range(3) for j,k in enumerate([0,1,3,4,5]))
    whites="".join(f'<div class="wk" data-id="key" data-note="{36+(i//7)*12+wn[i%7]}"><span style="position:absolute;bottom:12px;width:100%;text-align:center;font-family:\'Barlow Condensed\';font-size:12px;color:#9b968c;">{"C"+str(2+i//7) if i%7==0 else ""}</span></div>' for i in range(21))
    s=open(os.path.join(here,'skin.html')).read().replace('{{ROWS}}',rows).replace('{{CATS}}',cats).replace('{{BLACKS}}',blacks).replace('{{WHITES}}',whites)
    s=s.replace('<body>',f'<body class="m-{mode}">').replace('<html>',f'<html class="m-{mode}">')
    if mode in ('bg','on'): s=s.replace('class="ringwrap"','class="ringwrap ring"')
    p=os.path.join(here,f'_{mode}.html'); open(p,'w').write(s); return 'file://'+p
with sync_playwright() as pw:
    b=pw.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':1320,'height':820},device_scale_factor=2)
    pg=ctx.new_page()
    for mode in ('bg','on'):
        pg.goto(page(mode)); pg.wait_for_timeout(400)
        pg.screenshot(path=os.path.join(root,'Assets',f'skin_{mode}.png'),omit_background=(mode=='glass'))
    pg.goto(page('measure')); pg.wait_for_timeout(300)
    R=pg.evaluate('''()=>{const o={};for(const e of document.querySelectorAll('[data-id]')){const r=e.getBoundingClientRect();const k=e.dataset.id;(o[k]=o[k]||[]).push([r.x,r.y,r.width,r.height,+(e.dataset.note||0)])}return o}''')
    b.close()
def arr(name,lst): return f"    static const float {name}[][4] = {{ "+", ".join("{ %.1ff, %.1ff, %.1ff, %.1ff }"%tuple(r[:4]) for r in lst)+" };\n"
h="#pragma once\n// Generated by tools/skin/make_skin.py from the approved mockup: positions of the moving parts (1320 x 820)\nnamespace skin\n{\n"
for k in ['bpmlcd','bpm','screen','list','info','tag','num','name','desc','left','right','build','buildknob','cat','nav','knob','klab','kval','wheel','keys','row']:
    h+=arr(k,R[k])
keys=sorted(R['key'],key=lambda r:r[4])
h+="    struct Key { int note; float x, y, w, h; };\n    static const Key keyRects[] = { "+", ".join("{ %d, %.1ff, %.1ff, %.1ff, %.1ff }"%(r[4],r[0],r[1],r[2],r[3]) for r in keys)+" };\n}\n"
open(os.path.join(root,'Source','SkinRects.h'),'w').write(h)
print(json.dumps({k:len(v) for k,v in R.items()}))
